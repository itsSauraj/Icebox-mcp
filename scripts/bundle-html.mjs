/**
 * Inlines each built bundle into its own module under `generated/html/`, plus a
 * loader that imports them on demand.
 *
 * The previous version wrote one module holding every app's HTML in a single
 * object literal. That meant a cold start parsed every bundle into memory to
 * serve one app: with fifteen bundles at roughly 570 KB each that is about
 * 8 MB of string parsing before the first response. One module per app plus a
 * dynamic import means a cold start pays for the app that was actually asked
 * for.
 *
 * The import specifiers are literal strings so bundlers that trace serverless
 * functions (esbuild, ncc, the Vercel builder) can still follow them.
 *
 * Runs after `build-apps.mjs`, which produces `dist/*.html`.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { BUNDLED_FILES } from "../games/apps.mjs";

const root = process.cwd();
const distDir = path.join(root, "dist");
const outDir = path.join(root, "generated", "html");

/** `color-picker.html` becomes `color-picker`, safe as a module file name. */
const slug = (file) => file.replace(/\.html$/, "");

await fs.rm(outDir, { recursive: true, force: true });
await fs.mkdir(outDir, { recursive: true });

const missing = [];
let total = 0;

for (const file of BUNDLED_FILES) {
  let html;
  try {
    html = await fs.readFile(path.join(distDir, file), "utf-8");
  } catch {
    missing.push(file);
    continue;
  }
  total += html.length;
  const body =
    `// AUTO-GENERATED by scripts/bundle-html.mjs from dist/${file}. Do not edit.\n` +
    `export default ${JSON.stringify(html)};\n`;
  await fs.writeFile(path.join(outDir, `${slug(file)}.js`), body, "utf-8");
}

if (missing.length) {
  console.error(`bundle-html: missing built bundles: ${missing.join(", ")}`);
  console.error("Run `npm run build:apps` first.");
  process.exit(1);
}

const loaderEntries = BUNDLED_FILES.map(
  (file) => `  ${JSON.stringify(file)}: () => import("./${slug(file)}.js"),`,
).join("\n");

const loader = `// AUTO-GENERATED by scripts/bundle-html.mjs. Do not edit.
//
// One module per app, imported on demand, so serving one app does not parse the
// other fourteen. The specifiers are literal strings so serverless bundlers can
// trace them.

const loaders = {
${loaderEntries}
};

const cache = new Map();

/**
 * Resolve an app's bundled HTML by its built file name, e.g. "snake.html".
 * Throws if the file was never bundled, which means the build is stale.
 */
export async function loadHtml(file) {
  const hit = cache.get(file);
  if (hit) return hit;
  const load = loaders[file];
  if (!load) {
    throw new Error(\`No bundled HTML for "\${file}". Run \\\`npm run build\\\`.\`);
  }
  const mod = await load();
  cache.set(file, mod.default);
  return mod.default;
}

/** Every bundled file name. Useful for a build-time sanity check. */
export const BUNDLED = Object.keys(loaders);
`;

const types = `// AUTO-GENERATED by scripts/bundle-html.mjs. Do not edit.
export declare function loadHtml(file: string): Promise<string>;
export declare const BUNDLED: string[];
`;

await fs.writeFile(path.join(outDir, "index.js"), loader, "utf-8");
await fs.writeFile(path.join(outDir, "index.d.ts"), types, "utf-8");

// The old single-module form, if it is still lying around from a prior build.
await fs.rm(path.join(root, "generated", "html.js"), { force: true });
await fs.rm(path.join(root, "generated", "html.d.ts"), { force: true });

const mb = (total / 1024 / 1024).toFixed(2);
const avg = (total / BUNDLED_FILES.length / 1024).toFixed(0);
console.log(`bundle-html: ${BUNDLED_FILES.length} modules, ${mb} MB total, ${avg} KB average`);
